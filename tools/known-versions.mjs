// Collect every version of every macro this module has shipped: the packs in each commit of the git history plus the
// current packs/ folder. Writes scripts/known-versions.mjs, which the in-game updater uses to tell an outdated but
// unchanged imported macro (safe to update) from one that was edited in the world (left alone).
// Run before every release, after tools/pack.mjs:  node tools/known-versions.mjs
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import process from "node:process";
import { execFileSync } from "node:child_process";
import { PACKS, ROOT, loadClassicLevel } from "./lib.mjs";
import { fingerprint } from "../scripts/fingerprint.mjs";

const ClassicLevel = loadClassicLevel();
const OUT = path.join(ROOT, "scripts", "known-versions.mjs");
const known = {}; // macro id -> { scripts: Set<fingerprint>, icons: Set<img> }

async function collect(packsRoot, label) {
  let count = 0;
  for ( const pack of PACKS ) {
    const dir = path.join(packsRoot, path.relative(ROOT, pack.path));
    if ( !fs.existsSync(path.join(dir, "CURRENT")) ) continue;
    const db = new ClassicLevel(dir, { valueEncoding: "json" });
    for await ( const [key, doc] of db.iterator() ) {
      if ( !key.startsWith("!macros!") ) continue;
      const entry = known[doc._id] ??= { scripts: new Set(), icons: new Set() };
      entry.scripts.add(fingerprint(doc.command));
      if ( doc.img ) entry.icons.add(doc.img);
      count++;
    }
    await db.close();
  }
  console.log(`${label}: ${count} macros`);
}

const git = (...args) => execFileSync("git", args, { cwd: ROOT, encoding: "utf8" });
const commits = git("log", "--format=%h %s", "--", "packs").trim().split("\n").filter(Boolean);
const tmpRoot = fs.mkdtempSync(path.join(os.tmpdir(), "niks-macros-history-"));
try {
  for ( const line of commits ) {
    const [hash, ...subject] = line.split(" ");
    const dir = path.join(tmpRoot, hash);
    fs.mkdirSync(dir);
    execFileSync("sh", ["-c", `git archive ${hash} packs | tar -x -C "${dir}"`], { cwd: ROOT });
    await collect(dir, `${hash} ${subject.join(" ")}`);
  }
} finally {
  fs.rmSync(tmpRoot, { recursive: true, force: true });
}
await collect(ROOT, "working tree");

const data = Object.fromEntries(Object.keys(known).sort().map(id => [id, {
  scripts: [...known[id].scripts].sort(),
  icons: [...known[id].icons].sort()
}]));
fs.writeFileSync(OUT, `// Generated by tools/known-versions.mjs. Do not edit: run \`node tools/known-versions.mjs\` before a release.
// Every script fingerprint and icon each macro has shipped with, keyed by the macro's id in the compendium.
export default ${JSON.stringify(data, null, 2)};
`);
const versions = Object.values(data).reduce((n, d) => n + d.scripts.length, 0);
console.log(`Wrote ${path.relative(ROOT, OUT)}: ${Object.keys(data).length} macros, ${versions} script versions.`);
process.exitCode = 0;
